"""在服务端生成真正的 EPUB（零第三方依赖，zipfile 标准库实现）。"""
from __future__ import annotations

import io
import zipfile

from models import Book, Segment

_CHAPTER_TPL = """<?xml version="1.0" encoding="utf-8"?>
<html xmlns="http://www.w3.org/1999/xhtml" lang="zh">
<head><title>{title}</title>
<style>
body{{font-family:"Noto Serif CJK SC","Songti SC",serif;line-height:1.85;margin:0 6%}}
h1{{font-size:1.3em;text-align:center;margin:1em 0 .3em}}
h2{{font-size:1.05em;text-align:center;color:#555;font-weight:400;margin:0 0 1.6em}}
.seg{{margin-bottom:.9em}}
.s{{margin:0}}
.t{{margin:.2em 0 0;color:#1e40af;background:#eff6ff;padding:.35em .6em;
   border-left:3px solid #93c5fd;border-radius:0 .3em .3em 0}}
.f{{margin:.2em 0 0;color:#92400e;background:#fffbeb;padding:.35em .6em;
   border-left:3px solid #fcd34d}}
.note{{font-size:.8em;color:#888;text-align:center;margin-top:2em}}
</style></head>
<body>
<h1>{title}</h1>
<h2>双语对照版（{src} → {tgt}）</h2>
{body}
<p class="note">Generated by Bilingual E-Book Studio</p>
</body></html>
"""


def _esc(text: str | None) -> str:
    return (
        (text or "")
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
    )


def build_epub(book: Book, segments: list[Segment]) -> bytes:
    parts: list[str] = []
    for seg in segments:
        src = f'<p class="s">{_esc(seg.source_text)}</p>'
        tgt = (
            '<p class="f">⚠ 翻译失败，保留原文</p>'
            if seg.is_failed or not seg.translated_text
            else f'<p class="t">{_esc(seg.translated_text)}</p>'
        )
        parts.append(f'<div class="seg">{src}{tgt}</div>')

    chapter = _CHAPTER_TPL.format(
        title=_esc(book.title),
        src=book.source_lang,
        tgt=book.target_lang,
        body="\n".join(parts),
    )

    opf = f"""<?xml version="1.0" encoding="utf-8"?>
<package xmlns="http://www.idpf.org/2007/opf" version="3.0" unique-identifier="uid">
  <metadata xmlns:dc="http://purl.org/dc/elements/1.1/">
    <dc:identifier id="uid">bes-{book.id}</dc:identifier>
    <dc:title>{_esc(book.title)} 双语对照版</dc:title>
    <dc:language>zh</dc:language>
  </metadata>
  <manifest>
    <item id="ch1" href="ch1.xhtml" media-type="application/xhtml+xml"/>
    <item id="nav" href="nav.xhtml" media-type="application/xhtml+xml" properties="nav"/>
  </manifest>
  <spine><itemref idref="ch1"/></spine>
</package>"""

    nav = """<?xml version="1.0" encoding="utf-8"?>
<html xmlns="http://www.w3.org/1999/xhtml" xmlns:epub="http://www.idpf.org/2007/ops">
<head><title>目录</title></head>
<body><nav epub:type="toc"><ol><li><a href="ch1.xhtml">全文 · 双语对照</a></li></ol></nav></body>
</html>"""

    container = """<?xml version="1.0"?>
<container version="1.0" xmlns="urn:oasis:names:tc:opendocument:xmlns:container">
  <rootfiles>
    <rootfile full-path="OEBPS/content.opf" media-type="application/oebps-package+xml"/>
  </rootfiles>
</container>"""

    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as zf:
        # mimetype 必须是第一个条目且不压缩
        zf.writestr(zipfile.ZipInfo("mimetype"), "application/epub+zip", compress_type=zipfile.ZIP_STORED)
        zf.writestr("META-INF/container.xml", container, compress_type=zipfile.ZIP_DEFLATED)
        zf.writestr("OEBPS/content.opf", opf, compress_type=zipfile.ZIP_DEFLATED)
        zf.writestr("OEBPS/nav.xhtml", nav, compress_type=zipfile.ZIP_DEFLATED)
        zf.writestr("OEBPS/ch1.xhtml", chapter, compress_type=zipfile.ZIP_DEFLATED)
    return buf.getvalue()
